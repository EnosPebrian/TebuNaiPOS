import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

const origin = "http://127.0.0.1:3100";
const sale = () => ({ name: `Counter ${randomUUID()}`, phone: "", notes: "", paymentReceived: false, items: [{ configuredProduct: { productId: "nasi-bakar", configuration: { toppingIds: [] } }, quantity: 1 }] });

test("cashier creates protected, repriced counter sales and recovers lost responses without duplicates", async ({ page }, testInfo) => {
  const request = page.request;
  await page.goto("/admin/pos");
  await expect(page).toHaveURL(/\/admin\/login$/);
  const data = sale();
  const headers = { origin, "Idempotency-Key": randomUUID() };
  expect((await request.post("/api/admin/pos", { headers, data })).status()).toBe(401);
  expect((await request.get("/api/admin/reports")).status()).toBe(401);
  expect((await request.get("/api/admin/reports?format=csv")).status()).toBe(401);
  expect((await request.post("/api/admin/login", { headers: { origin }, data: { username: "e2e-owner", password: process.env.E2E_ADMIN_PASSWORD } })).status()).toBe(200);
  expect((await request.post("/api/admin/pos", { headers: { ...headers, origin: "https://evil.example" }, data })).status()).toBe(403);
  expect((await request.post("/api/admin/pos", { headers, data: { ...data, total: 1 } })).status()).toBe(400);
  const responses = await Promise.all(Array.from({ length: 3 }, () => request.post("/api/admin/pos", { headers, data })));
  for (const response of responses) expect(response.status()).toBe(201);
  const saved = (await responses[0].json()).order;
  for (const response of responses) expect((await response.json()).order.id).toBe(saved.id);
  expect(saved).toMatchObject({ source: "counter", subtotal: 19000, total: 19000, status: "confirmed", paymentStatus: "unpaid" });
  expect((await request.post("/api/admin/pos", { headers, data: { ...data, paymentReceived: true } })).status()).toBe(409);
  const records = await (await request.get("/api/admin/orders?view=kitchen")).json();
  const record = records.orders.find((entry: { order: { id: string } }) => entry.order.id === saved.id);
  expect(record.history[0]).toMatchObject({ actor: "e2e-owner", status: "confirmed", paymentStatus: "unpaid" });
  const paidSale = await request.post("/api/admin/pos", { headers: { origin, "Idempotency-Key": randomUUID() }, data: { ...sale(), name: "Private report customer", phone: "081234567890", paymentReceived: true } });
  expect(paidSale.status()).toBe(201);
  const paidId = (await paidSale.json()).order.id;
  expect((await request.patch(`/api/admin/orders/${paidId}`, { headers: { origin }, data: { version: 0, status: "cancelled", note: "Reporting fixture cancellation" } })).status()).toBe(200);
  const reportResponse = await request.get("/api/admin/reports");
  expect(reportResponse.status()).toBe(200);
  const reportData = await reportResponse.json();
  expect(reportData.rows.find((entry: { id: string }) => entry.id === paidId)).toMatchObject({ status: "cancelled", paymentStatus: "paid", receivedInPeriod: true, receivedAmount: 19000 });
  expect(reportData.cancelledReceivedValue).toBeGreaterThanOrEqual(19000);
  const csvResponse = await request.get("/api/admin/reports?format=csv");
  expect(csvResponse.headers()["content-type"]).toContain("text/csv");
  expect(csvResponse.headers()["cache-control"]).toContain("no-store");
  const csv = await csvResponse.text();
  expect(csv).toContain(paidId); expect(csv).not.toContain("Private report customer"); expect(csv).not.toContain("081234567890");
  expect((await request.get("/api/admin/reports?from=2026-02-30&to=2026-03-01")).status()).toBe(400);
  expect((await request.get("/api/admin/reports?format=pdf")).status()).toBe(400);
  await page.goto("/admin/reports");
  await expect(page.getByRole("heading", { name: "Sales reports", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Download CSV" })).toBeVisible();
  await expect(page).toHaveTitle(/Order administration/);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("sales-report.png"), fullPage: true });
  await page.goto("/admin/pos");
  await expect(page.getByRole("heading", { name: "Cashier", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Configure Sugar Cane Juice", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("radio", { name: /1500/ }).check();
  await dialog.getByRole("checkbox", { name: /Jeruk Nipis|Lime/i }).check();
  await dialog.getByRole("button", { name: "Add To Cart", exact: true }).click();
  await page.getByRole("button", { name: "Add Nasi Bakar", exact: true }).click();
  await expect(page.getByRole("region", { name: "Counter basket" })).toContainText(/59[.,]000/);
  await page.reload();
  await expect(page.getByRole("region", { name: "Counter basket" })).toContainText(/59[.,]000/);
  await page.getByLabel("Customer / pickup name").fill(`Cashier fixture ${testInfo.project.name}`);
  await page.getByLabel("I have received payment").check();
  await expect(page).toHaveTitle(/Order administration/);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.route("**/api/admin/pos", async (route) => { await route.fetch(); await route.abort("failed"); }, { times: 1 });
  await page.getByRole("button", { name: "Save counter sale", exact: true }).click();
  await expect(page.getByRole("button", { name: "Retry saved request" })).toBeEnabled();
  await page.reload();
  await page.getByRole("button", { name: "Retry saved request" }).click();
  await expect(page.getByText("Sale saved. Follow fulfillment in All orders or Kitchen queue.")).toBeVisible();
  await expect(page.getByText("Paid — recorded by staff", { exact: false })).toBeVisible();
  const afterRetry = await (await page.request.get("/api/admin/orders")).json();
  expect(afterRetry.orders.filter((entry: { order: { customer: { name: string } } }) => entry.order.customer.name === `Cashier fixture ${testInfo.project.name}`)).toHaveLength(1);
  await page.screenshot({ path: testInfo.outputPath("cashier-sale.png"), fullPage: true });
  const [slip] = await Promise.all([page.waitForEvent("popup"), page.getByRole("link", { name: "Print order slip" }).click()]);
  await expect(slip.getByRole("article", { name: "Order slip" })).toContainText("Counter sale");
  await expect(slip.getByRole("article", { name: "Order slip" })).toContainText(/59[.,]000/);
  await slip.close();
  await page.getByRole("button", { name: "New sale", exact: true }).click();
  await expect(page.getByText("Add products to start a sale.")).toBeVisible();
  await page.goto("/");
  await expect(page.getByRole("button", { name: /View cart/i })).not.toBeVisible();
  // Staff discovery composes filters and clamps a stale page to the available page.
  const today = new Date(Date.now() + 7 * 3_600_000).toISOString().slice(0, 10);
  const composed = await request.get(`/api/admin/orders?page=1000&reference=${paidId}&source=counter&payment=paid&method=pickup&status=cancelled&from=${today}&to=${today}`);
  expect(composed.status()).toBe(200);
  const matching = await composed.json();
  expect(matching.page).toBe(1); expect(matching.total).toBe(1); expect(matching.orders[0].order.id).toBe(paidId);
  expect((await (await request.get(`/api/admin/orders?reference=${paidId}&source=online`)).json()).total).toBe(0);
  expect((await (await request.get(`/api/admin/orders?reference=${paidId.slice(0, 8)}`)).json()).orders[0].order.id).toBe(paidId);
  expect((await request.get("/api/admin/orders?reference=12345678.*")).status()).toBe(400);
  expect((await request.get("/api/admin/orders?payment=paid&payment=unpaid")).status()).toBe(400);
  await page.goto("/admin");
  await page.getByLabel("Order reference", { exact: true }).fill(saved.id);
  await page.getByRole("combobox", { name: "Payment", exact: true }).click();
  await page.getByRole("option", { name: "Unpaid", exact: true }).click();
  await page.getByRole("button", { name: "Apply filters", exact: true }).click();
  await expect(page.getByRole("article")).toHaveCount(1);
  await expect(page.getByRole("article")).toContainText(data.name);
  await expect(page).toHaveTitle(/Order administration/);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("order-search.png"), fullPage: true });
  await page.getByRole("button", { name: "Manage order", exact: true }).click();
  await page.getByRole("button", { name: "Record payment received", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await expect(page.getByRole("article")).toHaveCount(0);
  await expect(page.getByText("Page 1", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Clear filters", exact: true }).click();
  await expect(page.getByLabel("Order reference", { exact: true })).toHaveValue("");
  // A new kitchen order appears on polling; editing a drawer pauses refresh.
  await page.clock.install();
  await page.goto("/admin/kitchen");
  await expect(page.getByLabel("Auto refresh every 30 seconds")).toBeChecked();
  let refreshRequests = 0;
  let failRefresh = false;
  await page.route("**/api/admin/orders?**", async (route) => { refreshRequests++; if (failRefresh) { failRefresh = false; await route.fulfill({ status: 503, json: { error: "Temporary queue failure" } }); } else await route.continue(); });
  const automaticName = `Auto kitchen ${testInfo.project.name}`;
  expect((await request.post("/api/admin/pos", { headers: { origin, "Idempotency-Key": randomUUID() }, data: { ...sale(), name: automaticName } })).status()).toBe(201);
  await page.clock.fastForward(31_000);
  await expect.poll(() => refreshRequests).toBe(1);
  await expect(page.getByRole("heading", { name: automaticName, exact: true })).toBeVisible();
  expect(refreshRequests).toBe(1);
  const autoCard = page.getByRole("article").filter({ has: page.getByRole("heading", { name: automaticName, exact: true }) });
  await autoCard.getByRole("button", { name: "Manage order" }).click();
  await page.getByLabel("Staff note").fill("Unsaved kitchen note");
  await page.clock.fastForward(31_000);
  expect(refreshRequests).toBe(1);
  await expect(page.getByLabel("Staff note")).toHaveValue("Unsaved kitchen note");
  await page.getByRole("button", { name: "Close order details" }).click();
  await page.clock.fastForward(31_000);
  await expect.poll(() => refreshRequests).toBe(2);
  await expect(page.getByRole("button", { name: "Refresh", exact: true })).toBeEnabled();
  failRefresh = true;
  await page.clock.fastForward(31_000);
  await expect(page.getByRole("alert").filter({ hasText: "Temporary queue failure" })).toBeVisible();
  await expect(page.getByRole("heading", { name: automaticName, exact: true })).toBeVisible();
  await page.clock.fastForward(31_000);
  await expect.poll(() => refreshRequests).toBe(4);
  await expect(page.getByRole("alert").filter({ hasText: "Temporary queue failure" })).not.toBeVisible();
  await page.getByLabel("Order reference", { exact: true }).fill("12345678");
  await page.clock.fastForward(31_000);
  expect(refreshRequests).toBe(4);
  await expect(page.getByLabel("Order reference", { exact: true })).toHaveValue("12345678");
});
