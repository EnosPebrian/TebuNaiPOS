import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

const origin = "http://127.0.0.1:3100";
const payload = (name: string, delivery = false) => ({
  items: [{ configuredProduct: { productId: "sugar-cane-juice", configuration: { packageId: "500ml", toppingIds: ["lime"] } }, quantity: 2 }],
  details: { name, phone: "081234567890", method: delivery ? "delivery" : "pickup", address: delivery ? "Jl. Test No. 10, Jakarta" : "", notes: "Test fixture only" },
});

test("saved orders, secure API access, idempotency, fees and conflicting edits", async ({ request }) => {
  expect((await request.get("/api/admin/orders")).status()).toBe(401);
  expect((await request.get("/api/orders")).status()).toBe(405);
  const input = payload(`API fixture ${randomUUID()}`, true);
  const key = randomUUID();
  const headers = { origin, "Idempotency-Key": key };
  expect((await request.post("/api/orders", { headers: { ...headers, origin: "https://evil.example" }, data: input })).status()).toBe(403);
  expect((await request.post("/api/orders", { headers, data: { ...input, subtotal: 1 } })).status()).toBe(400);
  expect((await request.post("/api/orders", { headers, data: { ...input, items: [{ configuredProduct: { productId: "sugarcane-rum-250ml", configuration: { toppingIds: [] } }, quantity: 1 }] } })).status()).toBe(400);
  const responses = await Promise.all(Array.from({ length: 3 }, () => request.post("/api/orders", { headers, data: input })));
  for (const response of responses) expect(response.status()).toBe(201);
  const saved = await responses[0].json();
  const id = saved.order.id as string;
  for (const response of responses) expect((await response.json()).order.id).toBe(id);
  expect(saved.order.subtotal).toBe(40000);
  expect(saved.order.total).toBeNull();
  expect((await request.post("/api/orders", { headers, data: { ...input, details: { ...input.details, notes: "Changed payload" } } })).status()).toBe(409);
  expect((await request.patch(`/api/admin/orders/${id}`, { headers: { origin }, data: { version: 0, status: "confirmed", note: "" } })).status()).toBe(401);
  expect((await request.post("/api/admin/login", { headers: { origin }, data: { username: "e2e-owner", password: "wrong-password" } })).status()).toBe(401);
  const login = await request.post("/api/admin/login", { headers: { origin }, data: { username: "e2e-owner", password: process.env.E2E_ADMIN_PASSWORD } });
  expect(login.status()).toBe(200);
  const cookie = (await request.storageState()).cookies.find((entry) => entry.name === "tebunai-admin");
  expect(cookie?.httpOnly).toBe(true);
  expect(cookie?.sameSite).toBe("Strict");
  expect(cookie?.value).not.toContain("e2e-owner");
  const listing = await request.get("/api/admin/orders");
  expect(listing.status()).toBe(200);
  const listingText = await listing.text();
  expect(listingText).not.toContain("fingerprint");
  expect(listingText).not.toContain("requestKey");
  expect((await request.patch(`/api/admin/orders/${id}`, { headers: { origin: "https://evil.example" }, data: { version: 0, status: "confirmed", deliveryFee: 10000, note: "" } })).status()).toBe(403);
  expect((await request.patch(`/api/admin/orders/${id}`, { headers: { origin }, data: { version: 0, status: "confirmed", note: "" } })).status()).toBe(400);
  const confirmed = await request.patch(`/api/admin/orders/${id}`, { headers: { origin }, data: { version: 0, status: "confirmed", deliveryFee: 10000, note: "Customer agreed delivery quote" } });
  expect(confirmed.status()).toBe(200);
  expect((await confirmed.json()).order.total).toBe(50000);
  const competing = await Promise.all(Array.from({ length: 2 }, () => request.patch(`/api/admin/orders/${id}`, { headers: { origin }, data: { version: 1, status: "preparing", note: "Kitchen accepted" } })));
  expect(competing.map((response) => response.status()).sort()).toEqual([200, 409]);
  const latest = (await (await request.get("/api/admin/orders")).json()).orders.find((record: { order: { id: string } }) => record.order.id === id);
  expect(latest.version).toBe(2);
  expect(latest.history).toHaveLength(3);
  expect(latest.history[1].deliveryFee).toBe(10000);
  expect(latest.history[2].actor).toBe("e2e-owner");
  expect((await request.post("/api/admin/logout", { headers: { origin } })).status()).toBe(200);
  expect((await request.get("/api/admin/orders")).status()).toBe(401);
});

test("staff can sign in, fulfill a saved order, record payment and sign out", async ({ page, request }, testInfo) => {
  const name = `Staff fixture ${testInfo.project.name}`;
  const created = await request.post("/api/orders", { headers: { origin, "Idempotency-Key": randomUUID() }, data: payload(name) });
  expect(created.status()).toBe(201);
  const savedId = (await created.json()).order.id as string;
  await page.goto(`/admin/orders/${savedId}/print`);
  await expect(page).toHaveURL(/\/admin\/login$/);
  const loginAxe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(loginAxe.violations).toEqual([]);
  await page.getByLabel("Username", { exact: false }).fill("e2e-owner");
  await page.getByLabel("Password", { exact: false }).fill(process.env.E2E_ADMIN_PASSWORD!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name, exact: true }) });
  await expect(card).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("admin-dashboard.png"), fullPage: true });
  const dashboardAxe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(dashboardAxe.violations).toEqual([]);
  await card.getByRole("button", { name: "Manage order" }).click();
  const dialog = page.getByRole("dialog", { name: "Order details" });
  const [unpaidSlip] = await Promise.all([page.waitForEvent("popup"), dialog.getByRole("link", { name: "Print order slip" }).click()]);
  await expect(unpaidSlip.getByRole("article", { name: "Order slip" })).toContainText("Unpaid");
  await expect(unpaidSlip.getByRole("article", { name: "Order slip" })).toContainText("awaiting merchant confirmation");
  await unpaidSlip.close();
  await dialog.getByRole("button", { name: "Mark confirmed" }).click();
  await expect(dialog).toContainText("Confirmed");
  await dialog.getByRole("button", { name: "Mark preparing" }).click();
  await dialog.getByRole("button", { name: "Mark ready" }).click();
  await dialog.getByRole("button", { name: "Mark completed" }).click();
  await expect(dialog.getByRole("alert")).toContainText("Record payment received");
  await dialog.getByLabel("Staff note").fill("Cash verified in person");
  await dialog.getByRole("button", { name: "Record payment received" }).click();
  await expect(dialog).toContainText("Payment: paid");
  await dialog.getByRole("button", { name: "Mark completed" }).click();
  await expect(dialog).toContainText("Completed");
  await expect(dialog).toContainText("Cash verified in person");
  const [slip] = await Promise.all([page.waitForEvent("popup"), dialog.getByRole("link", { name: "Print order slip" }).click()]);
  await expect(slip.getByRole("article", { name: "Order slip" })).toContainText("Paid — recorded by staff");
  await expect(slip.getByRole("article", { name: "Order slip" })).toContainText("Completed");
  await expect(slip.getByRole("table")).toContainText("500 ml");
  await expect(slip.getByRole("table")).toContainText(/40[.,]000/);
  await slip.screenshot({ path: testInfo.outputPath("order-slip.png"), fullPage: true });
  await slip.emulateMedia({ media: "print" });
  await expect(slip.getByRole("button", { name: "Print this slip" })).not.toBeVisible();
  await slip.close();
  await page.screenshot({ path: testInfo.outputPath("admin-order.png") });
  const detailAxe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(detailAxe.violations).toEqual([]);
  await page.getByRole("button", { name: "Close order details" }).click();
  await page.reload();
  await expect(card).toContainText("Completed");
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/login$/);
  await page.goto("/admin");
  await expect(page).toHaveURL(/\/admin\/login$/);
});

test("kitchen queue contains active orders oldest first and removes cancelled work", async ({ page }, testInfo) => {
  const request = page.request;
  await page.goto("/admin/kitchen");
  await expect(page).toHaveURL(/\/admin\/login$/);
  const login = await request.post("/api/admin/login", { headers: { origin }, data: { username: "e2e-owner", password: process.env.E2E_ADMIN_PASSWORD } });
  expect(login.status()).toBe(200);
  const ids: string[] = [];
  const suffix = `${testInfo.project.name}-${randomUUID().slice(0, 8)}`;
  for (const label of ["Old", "New", "Pending"]) {
    const response = await request.post("/api/orders", { headers: { origin, "Idempotency-Key": randomUUID() }, data: payload(`Kitchen ${label} ${suffix}`) });
    expect(response.status()).toBe(201);
    ids.push((await response.json()).order.id as string);
  }
  for (const id of ids.slice(0, 2)) expect((await request.patch(`/api/admin/orders/${id}`, { headers: { origin }, data: { version: 0, status: "confirmed", note: "Confirmed kitchen fixture" } })).status()).toBe(200);
  expect((await request.get("/api/admin/orders?view=kitchen&status=completed")).status()).toBe(400);
  const queue = await (await request.get("/api/admin/orders?view=kitchen")).json();
  const listedIds = queue.orders.map((record: { order: { id: string } }) => record.order.id) as string[];
  expect(listedIds.indexOf(ids[0])).toBeLessThan(listedIds.indexOf(ids[1]));
  expect(listedIds).not.toContain(ids[2]);
  await page.goto("/admin/kitchen");
  await expect(page.getByRole("heading", { name: "Kitchen queue", exact: true })).toBeVisible();
  await expect(page.getByText(`Kitchen Pending ${suffix}`, { exact: true })).not.toBeVisible();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: `Kitchen Old ${suffix}`, exact: true }) });
  await card.getByRole("button", { name: "Manage order" }).click();
  const dialog = page.getByRole("dialog", { name: "Order details" });
  await dialog.getByRole("button", { name: "Mark preparing" }).click();
  await dialog.getByRole("button", { name: "Mark ready" }).click();
  await dialog.getByLabel("Staff note").fill("Customer cancelled before pickup");
  await dialog.getByRole("button", { name: "Cancel order" }).click();
  await expect(dialog).not.toBeVisible();
  await expect(card).not.toBeVisible();
  const results = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(results.violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("kitchen-queue.png"), fullPage: true });
});
